import assert from 'node:assert/strict';
import { defensiveScenarioKey, rankedMatchupRoster, restoreDefensiveScenario, suggestDefensiveScenario } from '../lib/defensiveMatchups.ts';
const positions=['PG','SG','SF','PF','C'];
const away=positions.map((position,index)=>({player_id:index+1,full_name:`Atacante ${index+1}`,position}));
const home=positions.map((position,index)=>({player_id:index+11,full_name:`Defensor ${index+1}`,position}));
const averages=[...away,...home].map(player=>({player_id:player.player_id,min:30}));
const initial=suggestDefensiveScenario(away,home,averages);
assert.deepEqual(initial.away.map(row=>row.defenderId),[11,12,13,14,15]);
assert.equal(new Set(initial.away.map(row=>row.defenderId)).size,5);
const edited=structuredClone(initial);
edited.away[0]={attackerId:1,defenderId:15,origin:'manual'};
const restored=restoreDefensiveScenario(edited,away,home,averages);
assert.equal(restored.away[0].defenderId,15);
assert.deepEqual(restored.home,initial.home,'Cambiar una dirección conserva la otra');
assert.equal(restored.away[0].origin,'manual');
const absent=restoreDefensiveScenario({...restored,excluded:[15,2,999]},away,home,averages);
assert.deepEqual(absent.excluded,[15,2]);
assert.equal(absent.away[0].defenderId,null);
assert.equal(absent.away[0].origin,'pending');
assert.equal(absent.away[1].attackerId,null);
assert.equal(absent.home[4].attackerId,null);
assert.equal(absent.home[1].defenderId,null);
const invalid=structuredClone(initial);
invalid.away[1].attackerId=1;
invalid.away[2].defenderId=3;
const clean=restoreDefensiveScenario(invalid,away,home,averages);
assert.equal(clean.away[1].attackerId,null,'No se repite un atacante');
assert.equal(clean.away[2].defenderId,null,'El defensor pertenece al rival');
assert.deepEqual(restoreDefensiveScenario({version:9},away,home,averages),initial);
const short=suggestDefensiveScenario(away.slice(0,2),home.slice(0,1),averages);
assert.equal(short.away.length,5);
assert.equal(short.away.filter(row=>row.defenderId!==null).length,1);
assert.equal(short.away[4].origin,'pending');
assert.equal(rankedMatchupRoster(away,[{player_id:3,min:40}])[0].player_id,3);
assert.notEqual(defensiveScenarioKey('BOS','NYK','2026-10-20'),defensiveScenarioKey('BOS','NYK','2026-10-21'));
assert.notEqual(defensiveScenarioKey('BOS','NYK','2026-10-20'),defensiveScenarioKey('NYK','BOS','2026-10-20'));
console.log('OK: sugerencias, edición independiente, exclusiones, restauración, equipos y guardado por partido.');
